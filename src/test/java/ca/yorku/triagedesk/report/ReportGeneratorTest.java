package ca.yorku.triagedesk.report;

import static org.junit.jupiter.api.Assertions.assertEquals;
import static org.junit.jupiter.api.Assertions.assertThrows;
import static org.junit.jupiter.api.Assertions.assertTrue;

import ca.yorku.triagedesk.config.AppConfig;
import ca.yorku.triagedesk.detect.DetectionEngine;
import ca.yorku.triagedesk.domain.AttackTechnique;
import ca.yorku.triagedesk.domain.Case;
import ca.yorku.triagedesk.domain.Ioc;
import ca.yorku.triagedesk.domain.ResponsePlan;
import ca.yorku.triagedesk.domain.SecurityEvent;
import ca.yorku.triagedesk.domain.TriageVerdict;
import ca.yorku.triagedesk.domain.Verdict;
import ca.yorku.triagedesk.testutil.SampleData;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Clock;
import java.time.Instant;
import java.time.ZoneOffset;
import java.util.List;
import java.util.Map;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class ReportGeneratorTest {

    private static final Clock CLOCK = Clock.fixed(Instant.parse("2026-11-03T12:00:00Z"), ZoneOffset.UTC);

    @TempDir
    Path dir;

    private static Case sshCase() {
        Case c = new Case("CASE-0001", "Brute force from 203.0.113.7",
                DetectionEngine.withStandardDetectors(AppConfig.load(null, Map.of())).runAll(SampleData.authLog()), CLOCK);
        c.setIocs(List.of(Ioc.unscored(Ioc.IP, "203.0.113.7").withScore(87, "AbuseIPDB: confidence 87% | 120 reports")));
        c.setTechniques(List.of(new AttackTechnique("T1110.001", "Password Guessing", "Credential Access")));
        c.setVerdict(new TriageVerdict(Verdict.TRUE_POSITIVE, 0.9, "13 failures then a login.", List.of("count_by {} -> {}")));
        ResponsePlan plan = new ResponsePlan(List.of("Block 203.0.113.7", "Reset the deploy password"));
        plan.markDone(0);
        c.setResponsePlan(plan);
        c.addNote("Called the owner");
        return c;
    }

    @Test
    void reportContainsEverySectionAndLabelsTheAiParts() throws IOException {
        Path out = new ReportGenerator(CLOCK).generate(sshCase(), "### Executive summary\nAn attacker got in.", dir.resolve("r.md"));

        String md = Files.readString(out);
        assertTrue(md.startsWith("# Incident report: CASE-0001\n"));
        assertTrue(md.contains("Generated by TriageDesk on 2026-11-03T12:00:00Z"));
        for (String section : List.of("## Case details", "## Summary and analysis (AI-generated)", "## Findings",
                "## Timeline", "## Indicators of compromise", "## MITRE ATT&CK techniques",
                "## Triage verdict (AI-generated)", "## Response plan (AI-recommended)", "## Analyst notes", "## Case history")) {
            assertTrue(md.contains(section), "missing " + section);
        }
        assertTrue(md.contains("### Executive summary\nAn attacker got in."));
        assertTrue(md.contains("| Source IPs | 203.0.113.7 |"));
        assertTrue(md.contains("| Accounts | admin, deploy, oracle, root |"), md);
        assertTrue(md.contains("**TRUE_POSITIVE** (confidence 0.90)"));
        assertTrue(md.contains("- [x] Block 203.0.113.7\n- [ ] Reset the deploy password"));
        assertTrue(md.contains("AbuseIPDB: confidence 87% \\| 120 reports"), "pipes in cells are escaped");
        assertTrue(md.contains("| T1110.001 | Password Guessing | Credential Access |"));
    }

    @Test
    void missingNarrativeAndEmptySectionsAreExplained() {
        Case c = new Case("CASE-0002", "t",
                DetectionEngine.withStandardDetectors(AppConfig.load(null, Map.of())).runAll(SampleData.accessLog()), CLOCK);

        String md = new ReportGenerator(CLOCK).render(c, null);

        assertTrue(md.contains("## Summary and analysis (AI-generated)\n\n[AI narrative unavailable]"));
        assertTrue(md.contains("Not enriched yet."));
        assertTrue(md.contains("Not mapped yet."));
        assertTrue(md.contains("Not triaged yet."));
        assertTrue(md.contains("No response plan yet."));
    }

    @Test
    void timelineIsChronologicalAndCapped() {
        Case c = new Case("CASE-0002", "t",
                DetectionEngine.withStandardDetectors(AppConfig.load(null, Map.of())).runAll(SampleData.accessLog()), CLOCK);

        String timeline = new ReportGenerator(CLOCK).buildTimeline(c);

        List<String> rows = timeline.lines().filter(l -> l.startsWith("| 2026")).toList();
        assertEquals(37, rows.size());
        assertTrue(rows.get(0).startsWith("| 2026-10-28T10:30:01Z | apache |"));

        List<SecurityEvent> many = new java.util.ArrayList<>();
        for (int i = 0; i < 60; i++) {
            many.add(SecurityEvent.builder("e" + i, "b", Instant.parse("2026-10-28T09:00:00Z").plusSeconds(i)).message("m|x").build());
        }
        Case big = new Case("C", "t", List.of(new ca.yorku.triagedesk.domain.Finding("d", "t",
                ca.yorku.triagedesk.domain.Severity.LOW, null, null, null, null, null, null, many)), CLOCK);
        String capped = new ReportGenerator(CLOCK).buildTimeline(big);
        assertEquals(ReportGenerator.TIMELINE_LIMIT, capped.lines().filter(l -> l.startsWith("| 2026")).count());
        assertTrue(capped.contains("10 more events up to 2026-10-28T09:00:59Z are not listed."));
        assertTrue(capped.contains("m\\|x"));
    }

    @Test
    void unwritablePathIsReported() throws IOException {
        Path aDirectory = Files.createDirectory(dir.resolve("taken"));

        UncheckedIOException e = assertThrows(UncheckedIOException.class,
                () -> new ReportGenerator(CLOCK).generate(sshCase(), "x", aDirectory));
        assertTrue(e.getMessage().startsWith("Could not write report to "));
    }
}
