package ca.yorku.triagedesk.report;

import ca.yorku.triagedesk.domain.AttackTechnique;
import ca.yorku.triagedesk.domain.Case;
import ca.yorku.triagedesk.domain.Finding;
import ca.yorku.triagedesk.domain.Ioc;
import ca.yorku.triagedesk.domain.ResponsePlan;
import ca.yorku.triagedesk.domain.SecurityEvent;
import ca.yorku.triagedesk.domain.TriageVerdict;
import java.io.IOException;
import java.io.UncheckedIOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.time.Clock;
import java.time.temporal.ChronoUnit;
import java.util.List;
import java.util.Locale;
import java.util.Objects;
import java.util.TreeSet;
import java.util.function.Function;

/**
 * Builds the Markdown incident report (F11). Everything factual (case details, findings,
 * timeline, IOCs, techniques, verdict, plan, notes, history) is filled in by code from the
 * case; only the narrative passed in is AI-generated, and it is labelled as such.
 */
public class ReportGenerator {

    /** The timeline lists at most this many events; the rest are summarised in one line. */
    static final int TIMELINE_LIMIT = 50;
    static final String NARRATIVE_UNAVAILABLE = "[AI narrative unavailable]";

    private final Clock clock;

    public ReportGenerator() {
        this(Clock.systemUTC());
    }

    public ReportGenerator(Clock clock) {
        this.clock = clock;
    }

    /**
     * Writes the report and returns its path.
     *
     * @param narrative the AI-written summary and analysis, or null if the AI was unavailable
     * @throws UncheckedIOException "Could not write report ..." if the file cannot be written
     */
    public Path generate(Case c, String narrative, Path out) {
        String markdown = render(c, narrative);
        try {
            Path parent = out.toAbsolutePath().getParent();
            if (parent != null) {
                Files.createDirectories(parent);
            }
            Files.writeString(out, markdown, StandardCharsets.UTF_8);
            return out;
        } catch (IOException e) {
            throw new UncheckedIOException("Could not write report to " + out + " (" + e.getMessage() + ")", e);
        }
    }

    /** The report as Markdown text. */
    public String render(Case c, String narrative) {
        StringBuilder md = new StringBuilder();
        md.append("# Incident report: ").append(c.getId()).append("\n\n");
        md.append("**").append(inline(c.getTitle())).append("**\n\n");
        md.append("Generated by TriageDesk on ").append(clock.instant().truncatedTo(ChronoUnit.SECONDS))
                .append(". Sections marked *AI-generated* were written by the AI agent and must be checked by the analyst;"
                        + " everything else comes directly from the case data.\n\n");

        md.append("## Case details\n\n| Field | Value |\n|---|---|\n");
        row(md, "Case ID", c.getId());
        row(md, "Severity", c.getSeverity().name());
        row(md, "Priority", String.valueOf(c.getPriority()));
        row(md, "Status", c.getState().name() + (c.getResolution() != null ? " (" + c.getResolution() + ")" : ""));
        row(md, "Created", c.getCreatedAt().toString());
        List<SecurityEvent> events = c.getEvents();
        if (!events.isEmpty()) {
            row(md, "Activity", events.get(0).timestamp() + " to " + events.get(events.size() - 1).timestamp());
        }
        row(md, "Hosts", distinct(events, SecurityEvent::host));
        row(md, "Source IPs", distinct(events, SecurityEvent::srcIp));
        row(md, "Accounts", distinct(events, SecurityEvent::user));
        row(md, "Evidence events", String.valueOf(events.size()));
        md.append('\n');

        md.append("## Summary and analysis (AI-generated)\n\n");
        md.append(narrative == null || narrative.isBlank() ? NARRATIVE_UNAVAILABLE : narrative.strip()).append("\n\n");

        md.append("## Findings\n\n| Detector | Severity | Finding | First seen | Last seen | Events |\n|---|---|---|---|---|---|\n");
        for (Finding f : c.getFindings()) {
            md.append("| ").append(cell(f.detector())).append(" | ").append(f.severity()).append(" | ")
                    .append(cell(f.title())).append(" | ").append(f.firstSeen()).append(" | ").append(f.lastSeen())
                    .append(" | ").append(f.events().size()).append(" |\n");
        }
        md.append('\n');

        md.append("## Timeline\n\n").append(buildTimeline(c)).append('\n');

        md.append("## Indicators of compromise\n\n");
        if (c.getIocs().isEmpty()) {
            md.append("Not enriched yet.\n\n");
        } else {
            md.append("| Type | Value | Score (0-100) | Source |\n|---|---|---|---|\n");
            for (Ioc i : c.getIocs()) {
                md.append("| ").append(i.type()).append(" | ").append(cell(i.value())).append(" | ")
                        .append(i.isScored() ? String.valueOf(i.score()) : "n/a").append(" | ")
                        .append(cell(i.source())).append(" |\n");
            }
            md.append('\n');
        }

        md.append("## MITRE ATT&CK techniques\n\n");
        if (c.getTechniques().isEmpty()) {
            md.append("Not mapped yet.\n\n");
        } else {
            md.append("| ID | Technique | Tactics |\n|---|---|---|\n");
            for (AttackTechnique t : c.getTechniques()) {
                md.append("| ").append(t.id()).append(" | ").append(cell(t.name())).append(" | ")
                        .append(cell(t.tactic())).append(" |\n");
            }
            md.append('\n');
        }

        md.append("## Triage verdict (AI-generated)\n\n");
        TriageVerdict v = c.getVerdict();
        if (v == null) {
            md.append("Not triaged yet.\n\n");
        } else {
            md.append(String.format(Locale.ROOT, "**%s** (confidence %.2f)%n%n", v.verdict(), v.confidence()));
            md.append(v.reasoning().strip()).append("\n\n");
            if (!v.toolTrace().isEmpty()) {
                md.append("Evidence gathered by the agent:\n\n");
                v.toolTrace().forEach(t -> md.append("- `").append(t.replace("`", "'")).append("`\n"));
                md.append('\n');
            }
        }

        md.append("## Response plan (AI-recommended)\n\n");
        ResponsePlan plan = c.getResponsePlan();
        if (plan == null) {
            md.append("No response plan yet.\n\n");
        } else {
            for (int i = 0; i < plan.getSteps().size(); i++) {
                md.append("- [").append(plan.isDone(i) ? 'x' : ' ').append("] ").append(inline(plan.getSteps().get(i))).append('\n');
            }
            md.append('\n');
        }

        md.append("## Analyst notes\n\n");
        if (c.getNotes().isEmpty()) {
            md.append("None.\n\n");
        } else {
            c.getNotes().forEach(n -> md.append("- ").append(inline(n)).append('\n'));
            md.append('\n');
        }

        md.append("## Case history\n\n");
        c.getHistory().forEach(h -> md.append("- ").append(inline(h)).append('\n'));
        md.append("\n---\n*AI-generated content is informational and may contain mistakes; verify it against the evidence above.*\n");
        return md.toString();
    }

    /** The case's evidence events in time order, as a Markdown table. */
    String buildTimeline(Case c) {
        List<SecurityEvent> events = c.getEvents();
        StringBuilder md = new StringBuilder("| Time (UTC) | Source | Host | Account | Source IP | Event |\n|---|---|---|---|---|---|\n");
        for (SecurityEvent e : events.subList(0, Math.min(TIMELINE_LIMIT, events.size()))) {
            md.append("| ").append(e.timestamp()).append(" | ").append(cell(e.source())).append(" | ")
                    .append(cell(e.host())).append(" | ").append(cell(e.user())).append(" | ").append(cell(e.srcIp()))
                    .append(" | ").append(cell(e.message())).append(" |\n");
        }
        if (events.size() > TIMELINE_LIMIT) {
            md.append("\n").append(events.size() - TIMELINE_LIMIT).append(" more events up to ")
                    .append(events.get(events.size() - 1).timestamp()).append(" are not listed.\n");
        }
        return md.toString();
    }

    private static void row(StringBuilder md, String field, String value) {
        md.append("| ").append(field).append(" | ").append(cell(value)).append(" |\n");
    }

    private static String distinct(List<SecurityEvent> events, Function<SecurityEvent, String> f) {
        TreeSet<String> values = new TreeSet<>();
        events.stream().map(f).filter(Objects::nonNull).forEach(values::add);
        return values.isEmpty() ? "-" : String.join(", ", values);
    }

    /** A table cell: no line breaks, pipes escaped. */
    static String cell(String s) {
        if (s == null || s.isBlank()) {
            return "-";
        }
        return s.replace("\r", " ").replace("\n", " ").replace("|", "\\|").strip();
    }

    private static String inline(String s) {
        return s == null ? "" : s.replace("\r", " ").replace("\n", " ").strip();
    }
}
